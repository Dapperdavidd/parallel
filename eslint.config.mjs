import js from "@eslint/js";
import globals from "globals";
import tseslint from "typescript-eslint";
import nextPlugin from "@next/eslint-plugin-next";
import reactHooks from "eslint-plugin-react-hooks";

/**
 * One lint configuration for both halves of the repository.
 *
 * `next lint` used to be the only linter here, and it was unusable: it is
 * deprecated in Next 15, and with no config committed it stopped to ask an
 * interactive question, so it could never run in CI or in a hook. There was
 * therefore no linting at all.
 *
 * This replaces it with the ESLint CLI over the whole tree — the services in
 * `src/` and the app in `web/` — so one command covers both dependency trees.
 * Type-aware rules are deliberately left off: they need a program per package
 * and roughly a minute per run, and `tsc --noEmit` already runs in both
 * packages and is stricter about the things that matter.
 */
export default tseslint.config(
  {
    ignores: [
      "**/node_modules/**",
      "web/.next/**",
      "web/.next-build/**",
      "out/**",
      "data/**",
      "design-assets/**",
      // Upstream code, tracked for reference and not ours to restyle.
      "reference/**",
      "src/vendor/**",
      // A throwaway spike with its own package.
      "spike7/**",
      // Generated by Next on every build, and its triple-slash references
      // are required rather than stylistic.
      "web/next-env.d.ts",
    ],
  },
  js.configs.recommended,
  ...tseslint.configs.recommended,
  {
    languageOptions: {
      globals: { ...globals.node, ...globals.es2022 },
    },
    rules: {
      // The services print to the terminal on purpose; that is their output.
      "no-console": "off",
      eqeqeq: ["error", "always", { null: "ignore" }],
      "no-var": "error",
      "prefer-const": "error",
      "@typescript-eslint/no-unused-vars": [
        "error",
        { argsIgnorePattern: "^_", varsIgnorePattern: "^_" },
      ],
      // `any` is a smell, not a crime, and a few vendor boundaries need it.
      "@typescript-eslint/no-explicit-any": "warn",
      // Non-null assertions are used deliberately throughout, against
      // registry data whose shape is checked at the boundary.
      "@typescript-eslint/no-non-null-assertion": "off",
    },
  },
  {
    files: ["web/**/*.{ts,tsx}"],
    plugins: { "@next/next": nextPlugin, "react-hooks": reactHooks },
    settings: { next: { rootDir: "web" } },
    languageOptions: {
      globals: { ...globals.browser, ...globals.node },
    },
    rules: {
      ...nextPlugin.configs.recommended.rules,
      ...nextPlugin.configs["core-web-vitals"].rules,
      ...reactHooks.configs.recommended.rules,
    },
  },
  {
    // Test files generate throwaway values and assert on them.
    files: ["**/test/**/*.ts", "scripts/**/*.mjs"],
    rules: { "@typescript-eslint/no-unused-vars": "off" },
  },
);
